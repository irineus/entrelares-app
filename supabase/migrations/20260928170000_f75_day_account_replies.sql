-- =============================================================================
-- F-75 — the other caregiver can answer a relato: a reply appended to it,
-- never an edit
--
-- Decisions locked by the owner (28/09/2026, competitive chain):
--   * The word is "Resposta" / "Reply". One reply per member per relato, plus
--     ONE correction by the same author (a new row; both kept). No reply to a
--     reply.
--   * Who answers: an active caregiver with an account who is NOT the relato's
--     author. A Visualizador only reads (`refuse_viewer_write` on the table).
--   * Append-only by GRANT, the F-67 shape: the client has SELECT and nothing
--     else; the only writer is `add_day_account_reply`. Nothing is written in
--     care_schedules or activity_logs, so no admin_override can ever stamp it.
--   * Keys: day_account_reply.window_days (30, 7–90, counted from when the
--     relato was WRITTEN), day_account_reply.max_chars (the relato's default),
--     feature.day_account_replies (born false; production flips it in a later
--     migration). Free, like the relato.
--   * The notice goes in-app to the relato's author only, a new type
--     `day_account_reply` that the push dispatcher's filter does not name (so
--     no push, and nothing there changes). A viewer never authors a relato,
--     so the F-50 notification filter never meets it.
--   * Every FK cascades exactly as day_accounts' do (family, author, relato,
--     corrected reply): the family purge and purge_e2e_family, both under
--     app.deletion_context, take the replies with the family without naming
--     the table — the gate proves it.
--   * F-69 counts them (a total and the corrections), never their text.
-- =============================================================================

