-- ── 2. The table: append-only by GRANT, read by the whole family ─────────────

CREATE TABLE IF NOT EXISTS public.day_account_replies (
	id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	family_id         bigint NOT NULL REFERENCES public.families (id) ON DELETE CASCADE,
	account_id        bigint NOT NULL REFERENCES public.day_accounts (id) ON DELETE CASCADE,
	author_profile_id bigint NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
	body              text   NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000),
	corrects_id       bigint REFERENCES public.day_account_replies (id) ON DELETE CASCADE,
	created_at        timestamp with time zone DEFAULT timezone('utc', now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS day_account_replies_account_idx
	ON public.day_account_replies (account_id, created_at);
CREATE INDEX IF NOT EXISTS day_account_replies_family_idx
	ON public.day_account_replies (family_id, created_at);
-- One reply per member per relato (the original), and one correction of it.
CREATE UNIQUE INDEX IF NOT EXISTS day_account_replies_one_per_member_idx
	ON public.day_account_replies (account_id, author_profile_id) WHERE corrects_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS day_account_replies_one_correction_idx
	ON public.day_account_replies (corrects_id) WHERE corrects_id IS NOT NULL;

COMMENT ON TABLE public.day_account_replies IS
	'F-75: a reply to a relato do dia (day_accounts) by another caregiver. Append-only by GRANT; a correction is a new row pointing at the reply it corrects, both kept.';

